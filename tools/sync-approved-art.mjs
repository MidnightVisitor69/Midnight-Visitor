#!/usr/bin/env node
// sync-approved-art.mjs — Phase 2 (real art in the runtime collection).
//
// Reads the approved card manifests (source of truth) and does two things:
//   1. Emits `client/scripts/card/card_catalog.gd` — a compiled const index of
//      card_id -> {name, rarity, set_id, art_path}. It is a .gd (not a runtime
//      JSON) because the Android export preset ships resources + GDScript, not
//      loose non-resource files, so the catalog must be code to guarantee it
//      reaches the device. Nothing here invents data: every field is copied
//      verbatim from the manifest.
//   2. Stages each approved `base.png` into `client/art/<set>/<card_id>/base.png`,
//      the path CardArt loads via `res://art/<set>/<card_id>/base.png` (the
//      established Handoff Contract). Godot can only load from inside the
//      project, so this copy is required for the art to render on device;
//      `client/art/` is gitignored, so nothing binary enters the repo.
//
// Validation is strict: a manifest that is not approved, whose card_id does not
// match its folder, whose rarity is unknown, or whose base.png is missing or the
// wrong size is reported and SKIPPED (never silently mapped). Exit code is 1 if
// anything failed, so CI can gate on it.
//
// Usage:  node tools/sync-approved-art.mjs [--dry-run] [--no-stage]

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const APPROVED = path.join(ROOT, "shared", "art", "approved");
const ART_STAGE = path.join(ROOT, "client", "art");
const CATALOG_GD = path.join(ROOT, "client", "scripts", "card", "card_catalog.gd");

const VALID_RARITIES = new Set(["common", "rare", "epic", "legendary"]);
const WANT_W = 1024;
const WANT_H = 1536;

const dryRun = process.argv.includes("--dry-run");
const noStage = process.argv.includes("--no-stage");

// --- minimal PNG size reader (no deps): IHDR is at a fixed offset ------------
function pngSize(file) {
  const fd = fs.openSync(file, "r");
  try {
    const buf = Buffer.alloc(24);
    fs.readSync(fd, buf, 0, 24, 0);
    // 8-byte signature, then length(4)+ "IHDR"(4), then width(4) height(4).
    const isPng = buf.readUInt32BE(0) === 0x89504e47 && buf.toString("ascii", 12, 16) === "IHDR";
    if (!isPng) return null;
    return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
  } finally {
    fs.closeSync(fd);
  }
}

function gdEscape(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

const failures = [];
const cards = [];

if (!fs.existsSync(APPROVED)) {
  console.error(`sync-approved-art: missing approved dir ${APPROVED}`);
  process.exit(1);
}

const entries = fs
  .readdirSync(APPROVED, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

for (const dir of entries) {
  const full = path.join(APPROVED, dir);
  const manPath = path.join(full, "card.json");
  const pngPath = path.join(full, "base.png");

  let man;
  try {
    man = JSON.parse(fs.readFileSync(manPath, "utf8"));
  } catch (e) {
    failures.push(`${dir}: unreadable card.json (${e.message})`);
    continue;
  }

  if (man.approved !== true) {
    failures.push(`${dir}: not approved (approved=${JSON.stringify(man.approved)})`);
    continue;
  }
  if (man.card_id !== dir) {
    failures.push(`${dir}: card_id "${man.card_id}" does not match folder`);
    continue;
  }
  if (!VALID_RARITIES.has(man.rarity)) {
    failures.push(`${dir}: unknown rarity "${man.rarity}"`);
    continue;
  }
  if (!man.set) {
    failures.push(`${dir}: missing set`);
    continue;
  }
  if (!fs.existsSync(pngPath)) {
    failures.push(`${dir}: missing base.png`);
    continue;
  }
  const size = pngSize(pngPath);
  if (!size || size.w !== WANT_W || size.h !== WANT_H) {
    failures.push(`${dir}: base.png is ${size ? `${size.w}x${size.h}` : "not a PNG"}, want ${WANT_W}x${WANT_H}`);
    continue;
  }

  // art_path is relative to res://art/, matching CardArt._real_dir expectations.
  cards.push({
    card_id: man.card_id,
    // Player-facing display name; fall back to character_name then id so we
    // never emit an empty name (mirrors the importer's rule).
    name: man.name && String(man.name).trim() ? String(man.name) : (man.character_name || man.card_id),
    rarity: man.rarity,
    set_id: man.set,
    art_path: `${man.set}/${man.card_id}/base.png`,
  });
}

if (failures.length) {
  console.error("sync-approved-art: validation failures:");
  for (const f of failures) console.error("  - " + f);
}

// --- emit catalog .gd ---------------------------------------------------------
function emitCatalog() {
  const lines = [];
  lines.push("class_name CardCatalog");
  lines.push("extends RefCounted");
  lines.push("## GENERATED by tools/sync-approved-art.mjs — do not edit by hand.");
  lines.push("##");
  lines.push("## A compiled index of every approved card, copied verbatim from");
  lines.push("## shared/art/approved/*/card.json (the source of truth). It is a .gd");
  lines.push("## const rather than a runtime JSON so it ships inside the Android");
  lines.push("## export (resources + GDScript are packaged; loose non-resource files");
  lines.push("## are not, given the empty include_filter).");
  lines.push("##");
  lines.push("## art_path is relative to res://art/ and names the staged base.png that");
  lines.push("## CardArt loads. Cards are metadata only — presentation lives in");
  lines.push("## CardView, and loading/fallback lives in CardArt.");
  lines.push("");
  lines.push("const CARDS: Array[Dictionary] = [");
  for (const c of cards) {
    lines.push(
      `\t{ "card_id": "${gdEscape(c.card_id)}", "name": "${gdEscape(c.name)}", ` +
        `"rarity": "${gdEscape(c.rarity)}", "set_id": "${gdEscape(c.set_id)}", ` +
        `"art_path": "${gdEscape(c.art_path)}" },`
    );
  }
  lines.push("]");
  lines.push("");
  lines.push("");
  lines.push("static var _by_id: Dictionary = {}");
  lines.push("");
  lines.push("");
  lines.push("static func _index() -> Dictionary:");
  lines.push("\tif _by_id.is_empty():")
  lines.push("\t\tfor c in CARDS:")
  lines.push("\t\t\t_by_id[str(c[\"card_id\"])] = c")
  lines.push("\treturn _by_id");
  lines.push("");
  lines.push("");
  lines.push("static func has_card(card_id: String) -> bool:")
  lines.push("\treturn _index().has(card_id)");
  lines.push("");
  lines.push("");
  lines.push("## The full metadata record for a card, or an empty Dictionary if unknown.")
  lines.push("static func by_id(card_id: String) -> Dictionary:")
  lines.push("\treturn _index().get(card_id, {})");
  lines.push("");
  lines.push("");
  lines.push("## res://art-relative base.png path for a card, or \"\" if the card is not")
  lines.push("## in the catalog. CardArt uses this to resolve art when the incoming")
  lines.push("## art_path is empty or in a non-loadable form.")
  lines.push("static func art_path_for(card_id: String) -> String:")
  lines.push("\treturn str(by_id(card_id).get(\"art_path\", \"\"))");
  lines.push("");
  lines.push("");
  lines.push("static func all() -> Array[Dictionary]:")
  lines.push("\treturn CARDS");
  lines.push("");
  lines.push("");
  lines.push("## Distinct set ids, sorted — drives the collection's set selector.")
  lines.push("static func set_ids() -> Array[String]:")
  lines.push("\tvar seen: Array[String] = []")
  lines.push("\tfor c in CARDS:")
  lines.push("\t\tvar sid := str(c[\"set_id\"])")
  lines.push("\t\tif not seen.has(sid):")
  lines.push("\t\t\tseen.append(sid)")
  lines.push("\tseen.sort()")
  lines.push("\treturn seen");
  lines.push("");
  const out = lines.join("\n");
  if (dryRun) {
    console.log(`[dry-run] would write ${CARDS_GD_REL()} (${cards.length} cards)`);
    return;
  }
  fs.mkdirSync(path.dirname(CATALOG_GD), { recursive: true });
  fs.writeFileSync(CATALOG_GD, out, "utf8");
  console.log(`wrote ${path.relative(ROOT, CATALOG_GD)} (${cards.length} cards)`);
}

function CARDS_GD_REL() {
  return path.relative(ROOT, CATALOG_GD);
}

// --- stage base.png into client/art/<set>/<card_id>/ -------------------------
function stageArt() {
  if (noStage) {
    console.log("skipping art staging (--no-stage)");
    return;
  }
  let copied = 0;
  let skipped = 0;
  for (const c of cards) {
    const src = path.join(APPROVED, c.card_id, "base.png");
    const dstDir = path.join(ART_STAGE, c.set_id, c.card_id);
    const dst = path.join(dstDir, "base.png");
    if (dryRun) {
      console.log(`[dry-run] would stage ${path.relative(ROOT, src)} -> ${path.relative(ROOT, dst)}`);
      continue;
    }
    fs.mkdirSync(dstDir, { recursive: true });
    // Skip the copy when the destination is already byte-identical (fast re-run).
    if (fs.existsSync(dst)) {
      const a = fs.readFileSync(src);
      const b = fs.readFileSync(dst);
      if (a.equals(b)) {
        skipped += 1;
        continue;
      }
    }
    fs.copyFileSync(src, dst);
    copied += 1;
  }
  if (!dryRun) {
    console.log(`staged art into ${path.relative(ROOT, ART_STAGE)}: ${copied} copied, ${skipped} unchanged`);
  }
}

emitCatalog();
stageArt();

if (failures.length) {
  console.error(`sync-approved-art: ${failures.length} failure(s), ${cards.length} card(s) synced.`);
  process.exit(1);
}
console.log(`sync-approved-art: OK — ${cards.length} approved cards.`);
